<?php

declare(strict_types=1);

namespace ElastPro\Auth;

class HTTPAuth
{
    /**
     * Stored login credentials
     * @var array $auth_config
     */
    protected $auth_config;

    /**
     * Default login credentials
     * @var array $auth_default
     */
    private $auth_default = array(
        '0' => array(
        'admin_user' => 'admin',
        'admin_pass' => '$2y$10$.I8ji57GDlWHu6aWklGWZuTe57g980zelhV9VlYFyQfZ.eLd4b2/2',
        'purview' => RASPI_PURVIEW_ALL
        ));

    // Constructor
    public function __construct()
    {
        $this->auth_config = $this->getAuthConfig();
    }

    /*
     * Determines if user is logged in AND still exists in auth config.
     * If the user was deleted (e.g. via Authentication page), their session
     * is destroyed so they are immediately logged out.
     * return boolean
     */
    public function isLogged()
    {
        if (!isset($_SESSION['user_id'])) {
            return false;
        }

        // Verify the user still exists in the auth file.
        // A deleted user's session must be invalidated immediately.
        if (!$this->userExists($_SESSION['user_id'])) {
            $this->logoutSession();
            return false;
        }

        // A session must never outlive the boot it was created in. PHP keeps its
        // session files in /var/lib/php/sessions, which is persistent storage, so
        // without this check rebooting the device resumes the previous session
        // straight from the browser cookie — no login required.
        if ($this->isStaleBootSession()) {
            $this->logoutSession();
            return false;
        }

        return true;
    }

    /**
     * Returns a token that changes on every device reboot.
     */
    protected function getBootId(): string
    {
        // Generated by the kernel, unique per boot and world readable.
        $bootId = @file_get_contents('/proc/sys/kernel/random/boot_id');
        if ($bootId !== false && trim($bootId) !== '') {
            return trim($bootId);
        }

        // Fallback: PID 1 has existed since boot, so its directory mtime is the boot time.
        $bootTime = @filemtime('/proc/1');
        return $bootTime !== false ? (string) $bootTime : 'unknown';
    }

    /**
     * True when the session was created during an earlier boot.
     */
    protected function isStaleBootSession(): bool
    {
        // Sessions opened before this check existed carry no marker: bind them to the
        // running boot once, instead of logging every active user out at once.
        if (!isset($_SESSION['boot_id'])) {
            $_SESSION['boot_id'] = $this->getBootId();
            return false;
        }

        return !hash_equals($this->getBootId(), (string) $_SESSION['boot_id']);
    }

    /**
     * Check if a username still exists in the auth config file.
     */
    public function userExists(string $user): bool
    {
        $config = $this->getAuthConfig();
        foreach ($config as $entry) {
            if (is_array($entry) && isset($entry['admin_user']) && $entry['admin_user'] === $user) {
                return true;
            }
        }
        return false;
    }

    /**
     * Destroy the current session without redirect (used internally).
     */
    private function logoutSession(): void
    {
        // headers_sent() guard: once output has started the id can no longer be
        // rotated, but the session data is still wiped below.
        if (!headers_sent()) {
            session_regenerate_id(true);
        }
        session_unset();
        session_destroy();
    }

    /*
     * Authenticate a user using HTTP basic auth
     */
    public function authenticate()
    {
        if (!$this->isLogged()) {
            $redirectUrl = $_SERVER['REQUEST_URI'];
            if (strpos($redirectUrl, '/login') === false) {
                header('Location: /login?action=' . urlencode($redirectUrl));
                exit();
            }
        }
    }

    /*
     * Attempt to login a user with supplied credentials
     * @var string $user
     * @var string $pass
     * return boolean
     */
    public function login(string $user, string $pass)
    {
        if ($this->isValidCredentials($user, $pass)) {
            $_SESSION['user_id'] = $user;
            $_SESSION['login_time'] = time();
            $_SESSION['boot_id'] = $this->getBootId();
            return true;
        }
        return false;
    }

    /*
     * Logs out the administrative user
     */
    public function logout(): void
    {
        session_regenerate_id(true); // generate a new session id
        session_unset(); // unset all session variables
        session_destroy(); // destroy the session
        $redirectUrl = $_SERVER['REQUEST_URI'];
        if (strpos($redirectUrl, '/login') === false) {
            header('Location: /login?action=' . urlencode($redirectUrl));
            exit();
        }
    }

    /*
     * Gets the current authentication config
     * return array $config
     */
    public function getAuthConfig()
    {
        $config = $this->auth_default;

        if (file_exists(RASPI_ADMIN_DETAILS)) {
            if ($auth_details = fopen(RASPI_ADMIN_DETAILS, 'r')) {
                $i = 0;
                while (($line = fgets($auth_details)) !== false) {
                    // echo $i.':'.$line.PHP_EOL;
                    $result = explode(':', $line);
                    if (count($result) == 3) {
                        $config[$i]['admin_user'] = $result[0];
                        $config[$i]['admin_pass'] = $result[1];
                        $config[$i]['purview'] = $result[2];
                    }
                    
                    $i++;
                    unset($line);
                    unset($result);
                }
                // $config['admin_user'] = trim(fgets($auth_details));
                // $config['admin_pass'] = trim(fgets($auth_details));
                fclose($auth_details);
            }
        }

        return $config;
    }

    /*
     * Validates a set of credentials
     * @var string $user
     * @var string $pass
     * return boolean
     */
    protected function isValidCredentials(string $user, string $pass)
    {
        // return $this->validateUser($user) && $this->validatePassword($pass);
        $config = $this->getAuthConfig();
        $validated = false;
        foreach ($config as $key => $value) {
            if (is_array($value)) {
                if (isset($value['admin_user']) && $value['admin_user'] === $user) {
                    $validated = password_verify($pass, (string) $value['admin_pass']);
                    break;
                }
            } else {
                $validated = isset($config['admin_user']) && ($user === $config['admin_user'])
                    && password_verify($pass, (string) $config['admin_pass']);
                break;
            }
        }

        return $validated;
    }

    /**
     * Validates a user
     *
     * @param string $user
     */
    protected function validateUser(string $user)
    {
        return $user == $this->auth_config['admin_user'];
    }

    /**
     * Validates a password
     *
     * @param string $pass
     */
    protected function validatePassword(string $pass)
    {
        return password_verify($pass, $this->auth_config['admin_pass']);
    }

}
